-- ONLY IF Django connects as HOSTEL_APP and the nine objects are owned by
-- ANOTHER Oracle user (e.g., HOSTEL_OWNER). These GRANT statements must be
-- executed as the owner of the objects, not as HOSTEL_APP.
-- Change HOSTEL_APP below to your real Oracle API username before running.
-- This script does NOT create/drop/rename/change any of the nine tables.
--
-- Every function in Django uses unqualified identifiers; set
-- ORACLE_SCHEMA_OWNER=<actual owner> in .env on the app side.
--
-- DO NOT run this if Django connects as the schema owner: grants are unnecessary.
-- A DBA (not the project schema owner) must grant CREATE SESSION if needed:
-- GRANT CREATE SESSION TO HOSTEL_APP;
-- API reads and joins across the entire fixed schema.
GRANT SELECT ON ROOM TO HOSTEL_APP;
GRANT SELECT ON STUDENT TO HOSTEL_APP;
GRANT SELECT ON CATEGORY TO HOSTEL_APP;
GRANT SELECT ON STAFF TO HOSTEL_APP;
GRANT SELECT ON COMPLAINT TO HOSTEL_APP;
GRANT SELECT ON COMPLAINT_PHOTO TO HOSTEL_APP;
GRANT SELECT ON COMPLAINT_ASSIGNMENT TO HOSTEL_APP;
GRANT SELECT ON COMPLAINT_STATUS TO HOSTEL_APP;
GRANT SELECT ON COMPLAINT_FEEDBACK TO HOSTEL_APP;
GRANT SELECT ON V_COMPLAINT_DETAILS TO HOSTEL_APP;
GRANT SELECT ON V_DASHBOARD_SUMMARY TO HOSTEL_APP;
-- Direct DML in Django (business procedures handle all other writes).
GRANT INSERT ON ROOM TO HOSTEL_APP;
GRANT INSERT ON CATEGORY TO HOSTEL_APP;
GRANT INSERT ON STAFF TO HOSTEL_APP;
GRANT UPDATE (PASSWORD) ON STUDENT TO HOSTEL_APP;
GRANT UPDATE (NAME, DEPARTMENT, PHONE, STATUS, PASSWORD) ON STAFF TO HOSTEL_APP;
-- Django retrieves generated IDs using SELECT seq_<entity>.CURRVAL FROM dual.
GRANT SELECT ON SEQ_ROOM TO HOSTEL_APP;
GRANT SELECT ON SEQ_CATEGORY TO HOSTEL_APP;
GRANT SELECT ON SEQ_STAFF TO HOSTEL_APP;
GRANT SELECT ON SEQ_STUDENT TO HOSTEL_APP;
GRANT SELECT ON SEQ_COMPLAINT TO HOSTEL_APP;
-- Required business operations only (other six reporting procedures aren't
-- called by Django, although they remain in the fixed Oracle schema).
GRANT EXECUTE ON SP_REGISTER_STUDENT TO HOSTEL_APP;
GRANT EXECUTE ON SP_SUBMIT_COMPLAINT TO HOSTEL_APP;
GRANT EXECUTE ON SP_ADD_PHOTO TO HOSTEL_APP;
GRANT EXECUTE ON SP_ASSIGN_COMPLAINT TO HOSTEL_APP;
GRANT EXECUTE ON SP_UPDATE_STATUS TO HOSTEL_APP;
GRANT EXECUTE ON SP_SUBMIT_FEEDBACK TO HOSTEL_APP;
GRANT EXECUTE ON SP_ESCALATE_OVERDUE TO HOSTEL_APP;
